"use client";

import { useState } from "react";
import { motion } from "motion/react";
import { chartUrl } from "@/lib/format";
import { Section } from "./section";

function Figure({ path, version, label }: { path: string; version: string; label: string }) {
  const url = chartUrl(path, version);
  const [failed, setFailed] = useState(false);

  if (!url || failed) {
    return (
      <div className="border border-dashed border-[#c9c9c4] bg-surface p-6" role="alert">
        <p className="text-[15px] text-bad">The backend reported a chart, but it could not be loaded.</p>
        <p className="mt-2 break-all font-mono text-[12.5px] text-muted">{url ?? path}</p>
      </div>
    );
  }

  return (
    <motion.figure
      initial={{ opacity: 0, y: 14 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.45, ease: [0.23, 1, 0.32, 1] }}
      className="border border-line bg-surface p-3 sm:p-5"
    >
      {/* Remote backend asset with unknown dimensions; next/image adds nothing here. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={url} alt={label} onError={() => setFailed(true)} className="mx-auto block h-auto w-full max-w-[860px]" />
      <figcaption className="mt-3 break-all font-mono text-[12px] text-muted">{path}</figcaption>
    </motion.figure>
  );
}

export function ChartSection({ visualizations, sessionId, label }: { visualizations: string[]; sessionId: string; label: string }) {
  return (
    <Section title="Supporting visualization" note="Generated by the analysis tools.">
      {visualizations.length === 0 ? (
        <p className="text-[15px] text-muted">No visualization was produced for this question.</p>
      ) : (
        <div className="space-y-6">
          {visualizations.map((path) => (
            <Figure key={path} path={path} version={sessionId} label={label} />
          ))}
        </div>
      )}
    </Section>
  );
}

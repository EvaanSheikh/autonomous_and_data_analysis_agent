"use client";

import { Section } from "./section";

/** Shows the backend's final_report exactly as returned. */
export function ReportSection({ report }: { report: string }) {
  return (
    <Section title="Final report" note="Raw report generated by the backend.">
      {report.trim() === "" ? (
        <p className="text-[15px] text-muted">The backend returned no report.</p>
      ) : (
        <details className="group border border-line bg-surface">
          <summary className="mono-label flex cursor-pointer list-none items-center justify-between px-4 py-3 transition-colors hover:!text-ink">
            <span>
              <span className="mr-2 inline-block transition-transform duration-150 group-open:rotate-90" aria-hidden>
                ›
              </span>
              Report ({report.split("\n").length} lines)
            </span>
          </summary>
          <pre className="max-h-[480px] overflow-auto whitespace-pre-wrap break-words border-t border-line p-4 font-mono text-[12.5px] leading-6">
            {report}
          </pre>
        </details>
      )}
    </Section>
  );
}
